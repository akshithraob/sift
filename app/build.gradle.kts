// The "your data never leaves your phone" promise depends on the shipped APK having no network
// permission. Libraries can add one through manifest merging, so check the merged result.
val verifyNoInternetPermission = tasks.register("verifyNoInternetPermission") {
  val manifests = listOf("debug", "release", "demo").map { variant ->
    layout.buildDirectory.file("intermediates/merged_manifest/$variant/process${variant.replaceFirstChar { it.uppercase() }}MainManifest/AndroidManifest.xml")
  }
  dependsOn("processDebugMainManifest", "processReleaseMainManifest", "processDemoMainManifest")
  doLast {
    manifests.forEach { provider ->
      val file = provider.get().asFile
      check(file.exists()) { "Merged manifest not found: $file" }
      check(!file.readText().contains("android.permission.INTERNET")) {
        "android.permission.INTERNET is present in the merged manifest ($file). " +
          "Find the library that adds it in the manifest-merger report and remove it with tools:node=\"remove\"."
      }
    }
  }
}

tasks.matching { it.name in setOf("assembleDebug", "assembleRelease", "assembleDemo", "bundleRelease", "check") }
  .configureEach { dependsOn(verifyNoInternetPermission) }

// ---- Legal text -------------------------------------------------------------------------------
// assets/privacy_policy.md is filled in at runtime from res/values/legal.xml. These tasks keep the
// published copy in sync and stop a release from shipping with the placeholder contact address.
val exportPrivacyPolicy = tasks.register("exportPrivacyPolicy") {
  group = "legal"
  description = "Writes docs/privacy-policy.md (the policy with real values) for hosting at the Play Console URL."
  val legalXmlFile = file("src/main/res/values/legal.xml")
  val policyTemplateFile = file("src/main/assets/privacy_policy.md")
  val publishedPolicyFile = rootProject.file("docs/privacy-policy.md")
  inputs.files(legalXmlFile, policyTemplateFile)
  outputs.file(publishedPolicyFile)
  doLast {
    val values = Regex("<(?:string|integer) name=\"(\\w+)\"[^>]*>([^<]*)</")
      .findAll(legalXmlFile.readText()).associate { it.groupValues[1] to it.groupValues[2].trim() }
    val text = policyTemplateFile.readText()
      .replace("{{PUBLISHER}}", values.getValue("publisher_name"))
      .replace("{{PRIVACY_EMAIL}}", values.getValue("privacy_contact_email"))
      .replace("{{EFFECTIVE_DATE}}", values.getValue("policy_effective_date"))
      .replace("{{POLICY_VERSION}}", values.getValue("policy_version"))
    publishedPolicyFile.parentFile.mkdirs()
    publishedPolicyFile.writeText(text)
  }
}

val verifyLegalPlaceholders = tasks.register("verifyLegalPlaceholders") {
  group = "verification"
  description = "Fails a release build while the privacy contact email is still the placeholder."
  val legalXmlFile = file("src/main/res/values/legal.xml")
  inputs.file(legalXmlFile)
  doLast {
    val email = Regex("name=\"privacy_contact_email\"[^>]*>([^<]*)<")
      .find(legalXmlFile.readText())?.groupValues?.get(1)?.trim().orEmpty()
    check(email.contains("@") && !email.contains("REPLACE")) {
      "Set a real address for privacy_contact_email in res/values/legal.xml before building a release " +
        "(it is shown in the privacy policy and consent notice). Current value: '$email'"
    }
  }
}

tasks.matching { it.name in setOf("assembleRelease", "bundleRelease") }
  .configureEach { dependsOn(verifyLegalPlaceholders) }

// The shrunk (release/demo) build fails inside ML Kit on the first screenshot scan without its keep rules,
// while debug builds work, so nothing else would notice. Fail the build if the rules are removed.
val verifyMlKitKeepRules = tasks.register("verifyMlKitKeepRules") {
  group = "verification"
  description = "Fails a shrunk build if the ML Kit R8 keep rules are missing from proguard-rules.pro."
  val rules = file("proguard-rules.pro")
  inputs.file(rules)
  doLast {
    val text = rules.readText()
    check(text.contains("-keep class com.google.mlkit.** { *; }") && text.contains("ComponentRegistrar")) {
      "proguard-rules.pro must keep ML Kit classes. Without them, screenshot scanning fails in release builds."
    }
  }
}
tasks.matching { it.name.matches(Regex("(minify|assemble|bundle).*(Release|Demo)(WithR8)?")) }
  .configureEach { dependsOn(verifyMlKitKeepRules) }
